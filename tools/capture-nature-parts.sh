#!/usr/bin/env bash
# Renders the Creative nature props placed in a meadow in front of the wild models they were built from (rock deposit
# blocks, the wild Bush, meadow grass and flowers, the Leafy tree, the world's Tree Trunk and Fallen Log), together and
# close up (see game/tools/capture/CaptureScene.cs). Usage: tools/capture-nature-parts.sh OUT_DIR
# Needs a display; without one it uses xvfb-run. Uses $GODOT if set, otherwise the pinned build.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
godot="${GODOT:-$("$root/tools/install-godot.sh")}"
out="$(mkdir -p "${1:?usage: $0 OUT_DIR}" && cd "$1" && pwd)"
dotnet build "$root/Mechanica.sln" -c Debug
"$godot" --headless --path "$root/game" --import
run=()
[ -z "${DISPLAY:-}" ] && run=(xvfb-run -a -s "-screen 0 1280x720x24")
"${run[@]}" "$godot" --rendering-driver opengl3 --rendering-method gl_compatibility --path "$root/game" \
  res://tools/capture/CaptureScene.tscn -- "$out" nature_parts
